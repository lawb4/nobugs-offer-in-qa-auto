package expressjava.practice2.homework;

public class Point {

    private double x;
    private double y;

    public Point(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }

    public void setX(double x) {
        this.x = x;
    }

    public void print() {
        System.out.printf("x: %.2f, y: %.2f", x, y);
    }
}
